import type { PromptMode } from "@/lib/types";
import { MODE_INSTRUCTIONS } from "@/lib/modes";

export const SYSTEM_PROMPT = `Ты — старший промпт-инженер. Твоя задача — переписать промпт пользователя так, чтобы он давал стабильный и качественный результат.

Правила:
1. Сохраняй исходное намерение автора. Не добавляй задачи, которых он не просил.
2. Пиши на языке исходного промпта.
3. Структурируй результат блоками: Роль, Задача, Контекст, Требования, Формат вывода.
4. Не выдумывай факты о проекте пользователя — оставляй плейсхолдеры вида <укажите стек>.
5. Верни ТОЛЬКО улучшенный промпт, без пояснений и без markdown-обёртки вокруг всего текста.`;

export function buildUserMessage(prompt: string, mode: PromptMode): string {
  return `${MODE_INSTRUCTIONS[mode]}

Исходный промпт:
"""
${prompt}
"""

Перепиши его.`;
}
